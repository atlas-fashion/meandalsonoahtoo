"""The ForgeGUI kit: the dungeon pieces the Blender kit (build_dungeon_kit.py)
has none of, generated by ForgeGUI (Meshy, PBR) and fitted here onto the old
Tripo pieces' names, frames and sizes, so brick_level.gd swaps them in by name
and nothing that places them has to move. Note 184.

    blender -b --factory-startup --python tools/build_forge_kit.py

Reads models/source/forge/<source>.glb (the generations as they came back),
writes models/forge/forge_kit.glb. Never hand-edit the output; rebuild.

Every size below is the Tripo piece's bounding box in GODOT axes (x right,
y up, z out of the front), measured off models/brick/brick_kit.glb. In Blender
that is (x, -z, y): Godot +Z (a piece's front) is Blender -Y, and a glTF model
comes in facing Blender -Y, so a generation's front is already the front.
"""
import bpy, bmesh, os, sys, math
from mathutils import Vector, Matrix

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "models", "source", "forge")
OUT = os.path.join(ROOT, "models", "forge", "forge_kit.glb")

# piece: source glb, yaw (deg, about up, before fitting), Godot box (lo, hi),
# which axes stretch to the box ("fit") or keep the fitted axes' mean scale
# ("keep", centred in the box on that axis), triangle budget, texture size.
PIECES = {
    # The wooden door's leaf (module_level._build_brick_door, surgery_control):
    # as wide and tall as the Tripo leaf, centred in the arch's depth where it
    # stood (z -0.58), but 0.2 m of oak, not the Tripo cut's 0.84 m.
    "door_leaf": dict(src="door_leaf", box=((-0.999, 0.002, -0.68), (0.999, 4.192, -0.48)),
                      axes=("fit", "fit", "fit"), tris=2500, tex=2048),
    # The prison cells' gates (dungeon_room.gd): hinged at x = 0, the leaf out
    # along +x; the right leaf is its mirror.
    "jail_gate_l": dict(src="jail_gate", box=((0.0, 0.0, -0.1), (1.64, 4.74, 0.1)),
                        axes=("fit", "fit", "keep"), tris=4000, tex=1024, mirror="jail_gate_r"),
    # The band of carved wall over the prison's arcades, cornice to the front.
    "prison_frieze": dict(src="prison_frieze", box=((-3.351, 0.0, -0.947), (3.351, 3.496, 0.559)),
                          axes=("fit", "fit", "fit"), tris=6000, tex=2048, stone=True),
    # The morgue's burial walls: front face at z = 0, back 0.86 into the wall.
    "wall_loculi": dict(src="wall_loculi", box=((-1.95, 0.0, -0.858), (1.952, 2.815, 0.0)),
                        axes=("fit", "fit", "fit"), tris=9000, tex=2048, stone=True),
    # The morgue's slabs and the intro's altar: long along z.
    "morgue_slab": dict(src="morgue_slab", yaw=90.0, box=((-0.706, 0.0, -1.1), (0.706, 0.93, 1.1)),
                        axes=("fit", "fit", "fit"), tris=6000, tex=1024, stone=True),
    "manhole_cover": dict(src="manhole_cover", box=((-0.539, 0.0, -0.54), (0.539, 0.1, 0.54)),
                          axes=("fit", "fit", "fit"), tris=3000, tex=1024),
    # The prison's dome: a unit dome scaled up by dungeon_room._build_dome_hall,
    # seen only from inside -- its floor cut away and it turned inside out.
    "prison_dome": dict(src="prison_dome", box=((-1.0, 0.0, -1.0), (1.0, 1.486, 1.0)),
                        axes=("fit", "fit", "fit"), tris=16000, tex=2048, stone=True, inside_out=True),
    # The wall torch (torch.gd _wear_kit_mount): hangs below its origin, its
    # wall side at z = 0, its head TORCH_HEAD_OUT off the wall (torch.gd
    # KIT_HEAD_OUT). Built by _fit_torch, not the box.
    "torch_mount": dict(src="torch_mount", tris=3000, tex=1024, torch=True),
}
TORCH_HEIGHT = 1.44
TORCH_HEAD_OUT = 0.24
TORCH_WALL_GAP = 0.02
# Round the shaft's centre line: what is nearer the wall than this is bracket.
TORCH_SHAFT_R = 0.045


def log(*a):
    print("[forge_kit]", *a, flush=True)


def to_g(v):
    return Vector((v.x, v.z, -v.y))


def from_g(g):
    return Vector((g.x, -g.z, g.y))


def import_piece(src):
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=os.path.join(SRC, src + ".glb"))
    new = [o for o in bpy.data.objects if o not in before and o.type == "MESH"]
    for o in [o for o in bpy.data.objects if o not in before and o.type != "MESH"]:
        for c in o.children:
            mw = c.matrix_world.copy()
            c.parent = None
            c.matrix_world = mw
        bpy.data.objects.remove(o)
    bpy.ops.object.select_all(action="DESELECT")
    for o in new:
        o.select_set(True)
    bpy.context.view_layer.objects.active = new[0]
    if len(new) > 1:
        bpy.ops.object.join()
    obj = bpy.context.view_layer.objects.active
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    return obj


def godot_bounds(verts):
    gs = [to_g(v.co) for v in verts]
    lo = Vector((min(g.x for g in gs), min(g.y for g in gs), min(g.z for g in gs)))
    hi = Vector((max(g.x for g in gs), max(g.y for g in gs), max(g.z for g in gs)))
    return lo, hi


def fit_box(bm, spec):
    lo, hi = godot_bounds(bm.verts)
    tlo, thi = Vector(spec["box"][0]), Vector(spec["box"][1])
    ext, text = hi - lo, thi - tlo
    scale = [text[a] / ext[a] if spec["axes"][a] == "fit" else None for a in range(3)]
    fitted = [s for s in scale if s is not None]
    mean = sum(fitted) / len(fitted)
    scale = [s if s is not None else mean for s in scale]
    for v in bm.verts:
        g = to_g(v.co)
        out = Vector()
        for a in range(3):
            if spec["axes"][a] == "fit":
                out[a] = tlo[a] + (g[a] - lo[a]) * scale[a]
            else:
                out[a] = (tlo[a] + thi[a]) * 0.5 + (g[a] - (lo[a] + hi[a]) * 0.5) * scale[a]
        v.co = from_g(out)
    return scale


def fit_torch(bm):
    lo, hi = godot_bounds(bm.verts)
    s = TORCH_HEIGHT / (hi.y - lo.y)
    for v in bm.verts:
        v.co *= s
    lo, hi = godot_bounds(bm.verts)
    # The head: the top 15% of the torch, where the flame goes.
    cut = hi.y - (hi.y - lo.y) * 0.15
    head = [to_g(v.co) for v in bm.verts if to_g(v.co).y > cut]
    hx = sum(g.x for g in head) / len(head)
    hz = sum(g.z for g in head) / len(head)
    # The torch moves out whole so its head stands where torch.gd puts the
    # flame; only the bracket arm (below the head's 30%, behind the shaft)
    # stretches, so its plate still meets the wall.
    offset = TORCH_HEAD_OUT - hz
    split = hz - TORCH_SHAFT_R
    head_y = hi.y - (hi.y - lo.y) * 0.3
    k = (split + offset - TORCH_WALL_GAP) / (split - lo.z)
    for v in bm.verts:
        g = to_g(v.co)
        z = g.z + offset if g.z >= split or g.y >= head_y else TORCH_WALL_GAP + (g.z - lo.z) * k
        v.co = from_g(Vector((g.x - hx, g.y - hi.y, z)))
    log("torch: scale %.3f, bracket stretch %.3f" % (s, k))


def inside_out(bm):
    lo, hi = godot_bounds(bm.verts)
    floor = [f for f in bm.faces
             if to_g(f.normal).y < -0.5 and to_g(f.calc_center_median()).y < lo.y + (hi.y - lo.y) * 0.3]
    bmesh.ops.delete(bm, geom=floor, context="FACES")
    bmesh.ops.reverse_faces(bm, faces=bm.faces[:])
    log("dome: cut %d floor faces, turned inside out" % len(floor))


def decimate(obj, budget):
    tris = sum(len(p.vertices) - 2 for p in obj.data.polygons)
    if tris <= budget:
        return tris
    mod = obj.modifiers.new("dec", "DECIMATE")
    mod.ratio = budget / tris
    mod.use_collapse_triangulate = True
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.modifier_apply(modifier=mod.name)
    return sum(len(p.vertices) - 2 for p in obj.data.polygons)


def finish_material(obj, name, tex):
    for i, mat in enumerate(obj.data.materials):
        if mat is None:
            continue
        mat.name = "forge_%s" % name
        for n in mat.node_tree.nodes:
            if n.type == "TEX_IMAGE" and n.image:
                img = n.image
                role = "normal" if "normal" in img.name.lower() else "tex%d" % i
                for link in mat.node_tree.links:
                    if link.from_node == n:
                        sock = link.to_socket.name.lower()
                        if "color" in sock and "base" in link.to_node.name.lower() or sock == "base color":
                            role = "albedo"
                        elif link.to_node.type == "SEPRGB" or link.to_node.type == "SEPARATE_COLOR":
                            role = "orm"
                img.name = "forge_%s_%s" % (name, role)
                if img.size[0] > tex:
                    img.scale(tex, tex)


def build_piece(name, spec):
    obj = import_piece(spec["src"])
    obj.name = name
    obj.data.name = name
    if obj.data.has_custom_normals:
        bpy.context.view_layer.objects.active = obj
        bpy.ops.mesh.customdata_custom_splitnormals_clear()
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    yaw = math.radians(spec.get("yaw", 0.0))
    if yaw:
        bmesh.ops.rotate(bm, verts=bm.verts, cent=Vector(), matrix=Matrix.Rotation(yaw, 3, "Z"))
    if spec.get("torch"):
        fit_torch(bm)
    else:
        scale = fit_box(bm, spec)
        log("%s: scale %s" % (name, ", ".join("%.3f" % s for s in scale)))
    bm.normal_update()
    if spec.get("inside_out"):
        inside_out(bm)
    bm.to_mesh(obj.data)
    bm.free()
    tris = decimate(obj, spec["tris"])
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.shade_auto_smooth(angle=math.radians(50.0))
    finish_material(obj, name, spec["tex"])
    lo, hi = godot_bounds(obj.data.vertices)
    log("%s: %d tris, godot box (%.3f, %.3f, %.3f) .. (%.3f, %.3f, %.3f)" % (name, tris, *lo, *hi))
    out = [obj]
    if spec.get("mirror"):
        twin = obj.copy()
        twin.data = obj.data.copy()
        twin.name = twin.data.name = spec["mirror"]
        bpy.context.scene.collection.objects.link(twin)
        bm = bmesh.new()
        bm.from_mesh(twin.data)
        for v in bm.verts:
            v.co.x = -v.co.x
        bmesh.ops.reverse_faces(bm, faces=bm.faces[:])
        bm.normal_update()
        bm.to_mesh(twin.data)
        bm.free()
        out.append(twin)
    return out


def main():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    built = []
    for name, spec in PIECES.items():
        built += build_piece(name, spec)
    bpy.ops.object.select_all(action="DESELECT")
    for o in built:
        o.location = Vector()
        o.select_set(True)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=OUT, export_format="GLB", use_selection=True, export_animations=False,
        export_image_format="JPEG", export_image_quality=90, export_yup=True, export_apply=True,
        export_tangents=False,
    )
    log("wrote", OUT, os.path.getsize(OUT))


if __name__ == "__main__":
    main()
