"""The sewer's brick texture, made seamless.

    blender -b --factory-startup -P tools/build_sewer_texture.py

Source: models/source/sewer_hf/tex_brick.png -- generated by Higgsfield
(gpt_image_2_5, high) from the user's wall photo, asked to tile. Measured, it
tiles left-right (edge difference 0.069 against 0.060 between neighbouring
columns) but not top-bottom (0.119 against 0.069 between neighbouring rows).
Cross-fading the wrap ghosted a band of doubled mortar lines, so instead the
image is CROPPED between two rows that match (searched near the top and the
bottom: the pair, and the pairs of rows below them, most alike) and resized
back to square -- a whole number of courses, so it repeats. The normal map is
derived from the result's luminance (bricks proud, mortar sunk). Writes
textures/sewer_hf_albedo.png and textures/sewer_hf_normal.png.
"""
import os
import bpy
import numpy as np

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "models", "source", "sewer_hf", "tex_brick.png")
OUT = os.path.join(HERE, "textures")
SEARCH = 140


def main():
    im = bpy.data.images.load(SRC)
    w, h = im.size
    a = np.array(im.pixels[:]).reshape(h, w, 4)[:, :, :3].copy()  # row 0 = bottom
    best = None
    for y1 in range(0, SEARCH):
        for y2 in range(h - SEARCH, h - 2):
            d = sum(np.abs(a[y1 + k] - a[y2 + k]).mean() for k in range(0, 3) if y2 + k < h)
            if best is None or d < best[0]:
                best = (d, y1, y2)
    _, y1, y2 = best
    crop = a[y1:y2]
    # Back to h rows (nearest is fine at this scale: < 30% stretch).
    idx = np.clip((np.arange(h) * (crop.shape[0] / h)).astype(int), 0, crop.shape[0] - 1)
    a2 = crop[idx]
    lr = np.abs(a2[:, 0] - a2[:, -1]).mean()
    tb = np.abs(a2[0] - a2[-1]).mean()
    inner_c = np.mean([np.abs(a2[:, i] - a2[:, i + 1]).mean() for i in range(100, w - 100, 37)])
    inner_r = np.mean([np.abs(a2[i] - a2[i + 1]).mean() for i in range(100, h - 100, 37)])
    print("[sewer tex] cropped rows %d..%d; edges L-R %.4f (columns %.4f), T-B %.4f (rows %.4f)" % (
        y1, y2, lr, inner_c, tb, inner_r))
    lum = a2 @ np.array([0.2126, 0.7152, 0.0722])
    k = np.array([1, 4, 6, 4, 1], float) / 16
    for axis in (0, 1):
        lum = sum(np.roll(lum, i - 2, axis=axis) * k[i] for i in range(5))
    gy, gx = np.gradient(lum)
    s = 9.0
    nx, ny = -gx * s, gy * s
    nz = np.ones_like(nx)
    ln = np.sqrt(nx * nx + ny * ny + nz * nz)
    nrm = np.stack([nx / ln, ny / ln, nz / ln], -1) * 0.5 + 0.5
    for name, data in (("sewer_hf_albedo", a2), ("sewer_hf_normal", nrm)):
        img = bpy.data.images.new(name, w, h, alpha=False)
        if name.endswith("normal"):
            img.colorspace_settings.name = "Non-Color"
        px = np.ones((h, w, 4))
        px[..., :3] = np.clip(data, 0, 1)
        img.pixels = px.ravel()
        img.filepath_raw = os.path.join(OUT, name + ".png")
        img.file_format = "PNG"
        img.save()
        print("[sewer tex] wrote", img.filepath_raw)


main()
